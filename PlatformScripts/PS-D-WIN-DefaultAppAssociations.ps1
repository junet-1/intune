<#
.SYNOPSIS
    Intune Platform Script: Imports the corporate default app associations.

.DESCRIPTION
    Feeds an exported association list to DISM so file types and protocols open
    with the intended application for every profile created afterwards. The XML is
    embedded as Base64, so the script is self-contained. Runs as SYSTEM.

    The list was exported with
    DISM /Online /Export-DefaultAppAssociations:C:\Associations.xml on a reference
    device. To change it, re-export there and rebuild this script.

    Two entries carry intent beyond convenience:
      - PDF opens in Adobe Acrobat Reader DC (AcroExch.Document.DC) instead of Edge.
      - Script-shaped file types (bat, cmd, ps1, vbs, js, wsf, hta, reg, scr, ...)
        open in Notepad++ for viewing instead of executing on double-click.
    Both require the application to be installed before the user profile is
    created, otherwise Windows falls back to its own default.

    An association only changes what a double-click does - cmd /c, wscript,
    powershell -File and the right-click Run entry all still work. The target is
    the accidental double-click. PS-D-WIN-ScriptFileSafety.ps1 covers the cases
    this import cannot reach.

.NAME
    PS-D-WIN-DefaultAppAssociations

.RUNAS
    system

.RUN32
    false

.ENFORCESIGNATURE
    false

.NOTES
    Assign as Platform script. Run as SYSTEM (logged-on credentials: No). 64-bit: Yes.
    Applies to profiles created afterwards - existing users keep their choices.
    Exit 0 = success, non-zero = DISM failed.
#>

